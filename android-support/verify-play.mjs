import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=path=>readFileSync(path,'utf8');
const app=read('src/App.jsx');
const entry=read('src/main.jsx');
const login=read('src/android/AndroidLogin.jsx');
const deletion=read('src/android/AccountDeletion.jsx');
const access=read('src/android/AccessStatus.jsx');
const cfg=JSON.parse(read('capacitor.config.json'));
assert.equal(cfg.appId,'com.psctaiyari.psctaiyari');
assert.ok(entry.includes('HashRouter'),'Capacitor must use HashRouter for local navigation');
assert.ok(app.includes('<AndroidLogin/>'));
assert.ok(app.includes('<AccessStatus/>'));
assert.ok(app.includes('<AccountDeletion/>'));
assert.ok(app.includes('<Navigate to="/pricing" replace/>'),'Android payment route should not checkout');
assert.ok(!app.includes('<Payment/>'),'No Android QR payment route');
assert.ok(login.includes('https://psctaiyari.com'));
assert.ok(!login.includes('window.location.origin'),'Android email redirects must not use localhost');
assert.ok(deletion.includes('mailto:'));
assert.ok(deletion.includes('request-account-deletion'));
assert.ok(deletion.includes('https://psctaiyari.com/delete-account'));
assert.ok(!access.includes('/payment?plan='));
console.log('PASS: Android Play readiness: routes, checkout, authentication, account deletion');

const cards=read('src/android/AndroidCourses.jsx');
const checkout=read('src/android/DirectBuyButton.jsx');
const release=read('.github/workflows/android-release-aab.yml');
const debug=read('.github/workflows/android-debug-apk.yml');
assert.ok(app.includes('<AndroidCourses/>'));
assert.ok(app.includes('<AndroidCourse/>'));
assert.ok(app.includes('<AndroidDashboard/>'));
assert.ok(cards.includes('<DirectBuyButton'));
assert.ok(checkout.includes("VITE_ANDROID_DISTRIBUTION === 'direct'"),'Buy CTA must be gated by direct distribution');
assert.ok(checkout.includes('https://psctaiyari.com/pricing'));
assert.ok(release.includes('VITE_ANDROID_DISTRIBUTION: play'));
assert.ok(release.includes('verify-play-bundle.mjs'));
assert.ok(debug.includes('distribution:'));
console.log('PASS: external website Buy button only available in direct APK build');

const support=read('src/android/WebsiteSupport.jsx');
const lessons=read('src/android/AndroidCourse.jsx');
const listing=read('src/android/AndroidCourses.jsx');
assert.ok(app.includes('<WebsiteSupport/>'),'Website support route is available');
assert.ok(support.includes('https://psctaiyari.com/app-support.html'));
assert.ok(!support.includes('https://psctaiyari.com/pricing'),'Help URL cannot be checkout');
assert.ok(access.includes('psctaiyari.com'),'Subscription information must include website name');
assert.ok(!access.includes('<a href=')&&!access.includes('Browser.open'),'No external purchase link in entitlements');
assert.ok(lessons.includes(".eq('is_preview',true)"),'Demo must only use published preview lessons');
assert.ok(lessons.includes('डेमो पाठ अझै प्रकाशित भएको छैन'),'Do not invent sample lessons');
assert.ok(listing.includes('निःशुल्क पूर्वावलोकन'));
console.log('PASS: consumption-only website info, free preview and support-only web route');
